// Export Foundry ABIs + deployed addresses as typed TypeScript (`as const`) for viem/wagmi.
// Run via `npm run abi` (builds first). Output: abi/*.ts (committed).
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "abi");
const contracts = [
  { name: "GameUSDC", constName: "gameUsdcAbi" },
  { name: "USDCFaucet", constName: "usdcFaucetAbi" },
  { name: "GameVault", constName: "gameVaultAbi" },
  { name: "RoomManager", constName: "roomManagerAbi" },
  { name: "NativeGameVault", constName: "nativeGameVaultAbi" },
];
const header = "// Generated by scripts/export-abi.mjs — do not edit by hand.\n";

mkdirSync(outDir, { recursive: true });
const indexLines = [header];

for (const { name, constName } of contracts) {
  const artifact = join(root, "out", `${name}.sol`, `${name}.json`);
  if (!existsSync(artifact)) throw new Error(`Missing ${artifact}. Run \`forge build\` first.`);
  const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
  writeFileSync(
    join(outDir, `${name}.ts`),
    `${header}\nexport const ${constName} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  indexLines.push(`export { ${constName} } from "./${name}";`);
}

// Deployed proxy addresses per chain id (local anvil deployments are not exported).
const deployments = {};
const depDir = join(root, "deployments");
if (existsSync(depDir)) {
  for (const file of readdirSync(depDir).filter((f) => f.endsWith(".json"))) {
    const data = JSON.parse(readFileSync(join(depDir, file), "utf8"));
    if (data.chainId === 31337) continue;
    deployments[data.chainId] = {
      GameUSDC: data.GameUSDC,
      USDCFaucet: data.USDCFaucet,
      GameVault: data.GameVault,
      RoomManager: data.RoomManager,
    };
  }
}
writeFileSync(
  join(outDir, "deployments.ts"),
  `${header}
export type ContractAddresses = {
  GameUSDC: \`0x\${string}\`;
  USDCFaucet: \`0x\${string}\`;
  GameVault: \`0x\${string}\`;
  RoomManager: \`0x\${string}\`;
};

/** Proxy addresses by chain id (10143 = Monad testnet). */
export const deployments: Record<number, ContractAddresses> = ${JSON.stringify(deployments, null, 2)};
`,
);
indexLines.push(`export { deployments, type ContractAddresses } from "./deployments";`);

// Native deployments are isolated from legacy USDC addresses. Missing deployment stays missing.
const nativeDeployments = {};
const nativeDir = join(depDir, "native");
if (existsSync(nativeDir)) {
  for (const file of readdirSync(nativeDir).filter((f) => f.endsWith(".json"))) {
    const data = JSON.parse(readFileSync(join(nativeDir, file), "utf8"));
    if (data.chainId === 31337) continue;
    if (
      data.chainId !== 10143 ||
      data.asset !== "MON" ||
      data.decimals !== 18 ||
      !/^0x[0-9a-fA-F]{40}$/.test(data.NativeGameVault) ||
      /^0x0{40}$/.test(data.NativeGameVault) ||
      !/^0x[0-9a-fA-F]{64}$/.test(data.deploymentTxHash)
    ) {
      throw new Error(`Invalid native deployment record: ${file}`);
    }
    nativeDeployments[data.chainId] = { NativeGameVault: data.NativeGameVault };
  }
}
writeFileSync(
  join(outDir, "nativeDeployments.ts"),
  `${header}
export type NativeContractAddresses = { NativeGameVault: \`0x\${string}\` };
/** Confirmed native deployments only. Empty until a real deployment is recorded. */
export const nativeDeployments: Record<number, NativeContractAddresses> = ${JSON.stringify(nativeDeployments, null, 2)};
`,
);
indexLines.push(`export { nativeDeployments, type NativeContractAddresses } from "./nativeDeployments";`);
writeFileSync(join(outDir, "index.ts"), indexLines.join("\n") + "\n");
console.log(`Exported ${contracts.length} ABIs and ${Object.keys(deployments).length} deployment(s) to abi/`);
